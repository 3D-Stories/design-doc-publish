def test_the_normalisation_contract_this_guard_depends_on():
    """Step 11 (Medium) asked for `_url_value`'s contract to be auditable from here, because
    `_safe_url`'s security now rests on a helper in another module.

    Reimplementing it locally was DECLINED — that would fork a definition this codebase
    deliberately keeps single, the same reason `_is_external` is imported rather than copied
    (#23). The real risk is cross-module drift, so the contract is pinned instead: if
    `lint._url_value` ever stops stripping leading C0 controls or removing TAB/LF/CR, this test
    fails right next to the guard that relies on it.
    """
    from render.lint import _url_value
    assert _url_value("\x01//host") == "//host", "leading C0 controls must be stripped"
    assert _url_value("//host\x01") == "//host", "trailing C0 controls must be stripped"
    assert _url_value(" //host ") == "//host", "leading/trailing spaces must be stripped"
    assert _url_value("/\t/\r\n/host") == "///host", "TAB/LF/CR must be removed ANYWHERE"
    assert _url_value("a\x1fb") == "a\x1fb", "an INTERIOR C0 control is not stripped"
    # and the consequence the guard actually cares about
    assert md._safe_url("\x01//evil.example/x") is None


