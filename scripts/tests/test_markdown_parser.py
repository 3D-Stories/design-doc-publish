# --- the move, and the trap the empty module's docstring names -------------------

def test_parser_lives_in_markdown_module():
    """The parser moved out of __init__ into render/markdown.py."""
    for name in ("_inline", "_render_body_plain", "_render_roadmap",
                 "_is_table_separator", "_split_table_row"):
        assert hasattr(md, name), f"render.markdown must own {name}"


def test_inline_fn_is_a_call_time_lookup_not_a_def_time_default():
    """THE trap. A def-time default binds the ORIGINAL `_inline`, so replacing it
    would never reach a direct caller and the parser fix would be silently inert.

    Both renderers must resolve `_inline` at CALL time. Proven by swapping the
    module attribute and checking the swap is observed.
    """
    original = md._inline
    try:
        md._inline = lambda esc: "SWAPPED"
        assert "SWAPPED" in md._render_body_plain("hello"), (
            "_render_body_plain captured _inline at definition time"
        )
        assert "SWAPPED" in md._render_roadmap("## Heading\n\nhello"), (
            "_render_roadmap captured _inline at definition time"
        )
    finally:
        md._inline = original


# --- AC2: plain is byte-identical ------------------------------------------------

PROBE = """# Doc Title

Intro with a [link](https://example.com), *italic*, _under_ and **bold**.

1. first
2. second
3. third

- parent
  - nested child
- sibling

![alt text](https://example.com/i.png)

---

Done.
"""


def test_plain_output_is_unchanged_for_every_construct():
    """AC2: plain must still emit the raw markdown it always did — no <ol>, no <a>,
    no <em>, no <img>, no <hr>. This is the byte-identity contract, asserted as
    behaviour so a well-meaning 'fix' to plain fails here."""
    out = render._render_body(PROBE, style="plain")
    for tag in ("<ol>", "<a ", "<em>", "<img", "<hr"):
        assert tag not in out, f"plain must not gain {tag} (AC2 byte-identity)"
    assert "[link](https://example.com)" in out, "plain still shows the literal link"


def test_plain_matches_a_frozen_snapshot():
    """AC2 the blunt way: plain's bytes for the probe are FROZEN.

    The fixture was generated by rendering PROBE with the engine at `origin/main`
    BEFORE this change, and a differential run over five documents (probe, tables,
    fenced code, soft-wrap, hostile input) confirmed old == new for `plain` in every
    one. This pin is what keeps that true — any future edit that changes plain's
    output fails here with a byte diff.
    """
    frozen = (Path(__file__).parent / "fixtures" / "plain_probe_frozen.html").read_text()
    assert render._render_body(PROBE, style="plain") == frozen, (
        "plain output changed — AC2 forbids it; the new constructs belong behind "
        "the inline_fn seam and rich=True"
    )


def test_plain_still_corrupts_ordered_lists_on_purpose():
    """Uncomfortable but correct: AC2 pins plain, so plain KEEPS the run-on
    paragraph. The fix lands for every richer template. Asserting it explicitly
    stops someone 'helpfully' fixing plain and silently breaking byte-identity."""
    out = render._render_body(PROBE, style="plain")
    assert "1. first" in out and "<ol>" not in out


