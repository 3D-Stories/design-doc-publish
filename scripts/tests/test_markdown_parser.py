"""#16 wave 1: the seven constructs the renderer silently emitted as raw markdown.

Two hard rules this file exists to enforce:

* AC2 — `plain` stays BYTE-IDENTICAL. The new transforms are gated behind the
  `inline_fn` seam and a block-level `rich` switch; `plain` keeps today's `_inline`
  and today's block loop. Every richer style gets the fix.
* AC3 — escape-first. New transforms run on ALREADY-ESCAPED text and can never
  introduce an unescaped `<`.

The parser also MOVES to `render/markdown.py`, and the two def-time
`inline_fn=_inline` defaults become call-time lookups — without that, a fixed
`_inline` never reaches direct callers and the whole fix is inert.
"""
import re
import sys
from pathlib import Path

import pytest

SCRIPTS = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SCRIPTS))

import render  # noqa: E402
