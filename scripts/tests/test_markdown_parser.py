def test_emphasis_never_runs_inside_generated_markup():
    """Step 11 #1 (High): emphasis ran over HTML this renderer had just generated, so
    an asterisk in a URL became a TAG INSIDE AN href — a structural break of
    escape-first, not merely cosmetic."""
    out = render._render_body("[x](https://e/*p*)\n", style="design")
